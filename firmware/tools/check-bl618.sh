# Syntax and type check of the BL618 firmware against the Bouffalo SDK's headers, on a Mac
# with no RISC-V GCC: Homebrew LLVM's RISC-V target plus newlib's headers. **Not a build** —
# nothing links and nothing is optimised; the real build is `make` with the SDK's T-HEAD
# toolchain (firmware/bl618_rtl_udp/README.md). What it does catch is every wrong type,
# missing declaration and misspelt SDK call, before there is hardware to flash.
#
#   firmware/tools/fetch-deps.sh bl618    # the SDK and newlib headers, once
#   firmware/tools/check-bl618.sh         # all sources; or name some
set -eu
here=$(cd "$(dirname "$0")/.." && pwd)
B="$here/deps/bouffalo_sdk"
N="$here/deps/newlib/newlib/libc/include"
STUB="$here/deps/newlib-stub"
CC=${CC:-/usr/local/opt/llvm/bin/clang}
[ -x "$CC" ] || CC=$(ls -d /usr/local/opt/llvm*/bin/clang /opt/homebrew/opt/llvm*/bin/clang 2>/dev/null | head -1)

# newlib.h is generated by newlib's configure; this is the part of it the headers read.
mkdir -p "$STUB"
[ -f "$STUB/newlib.h" ] || printf '#pragma once\n#define _NEWLIB_VERSION "4.4.0"\n#define __NEWLIB__ 4\n#define __NEWLIB_MINOR__ 4\n#define _WANT_IO_LONG_LONG 1\n#define _MB_LEN_MAX 1\n' > "$STUB/newlib.h"

INC="-I$here/bl618_rtl_udp -I$here/bl618_rtl_udp/config -I$here/common/librtlsdr -I$STUB -I$N
 -I$B/components/os/freertos/include -I$B/components/os/freertos/portable/GCC/RISC-V/common
 -I$B/drivers/lhal/include -I$B/drivers/lhal/config/bl616 -I$B/drivers/soc/bl616/std/include
 -I$B/drivers/lhal/include/arch -I$B/drivers/lhal/include/arch/risc-v/t-head
 -I$B/drivers/lhal/include/arch/risc-v/t-head/Core/Include -I$B/bsp/board/bl616dk
 -I$B/components/usb/cherryusb -I$B/components/usb/cherryusb/core -I$B/components/usb/cherryusb/common
 -I$B/components/usb/cherryusb/class/hub
 -I$B/components/net/lwip/lwip/src/include -I$B/components/net/lwip/lwip/lwip-port
 -I$B/components/wireless/wifi6/wifi6_lwip_adapter/include -I$B/components/wireless/wifi6/fhost/include
 -I$B/components/wireless/wifi6/include -I$B/components/wireless/macsw/inc
 -I$B/components/utils/async_event -I$B/drivers/rfparam/Inc -I$B/drivers/soc/bl616/phyrf/include"
# The FreeRTOS port's own definitions (components/os/freertos/CMakeLists.txt).
DEFS="-DBL616 -DCONFIG_FREERTOS -DCONFIG_CHERRYUSB_HOST -DCONFIG_PSRAM -DHIGH_PERFORMANCE_PBUF=1
 -DconfigMTIME_BASE_ADDRESS=0xE000BFF8 -DconfigMTIMECMP_BASE_ADDRESS=0xE0004000"

if [ $# -eq 0 ]; then
  set -- "$here"/bl618_rtl_udp/*.c "$here"/common/librtlsdr/*.c
fi
status=0
for f in "$@"; do
  # librtlsdr is upstream's, unmodified: its own unused helpers are not ours to fix, so it
  # is checked for errors only.
  case "$f" in */librtlsdr/*) W="-w" ;; *) W="-Wall -Wextra -Wno-unused-parameter" ;; esac
  # Two macro redefinitions between lwIP's and newlib's endian headers are the headers'
  # business, not ours, and appear in every file that includes lwIP.
  out=$("$CC" --target=riscv32-unknown-elf -march=rv32imafc -mabi=ilp32f -ffreestanding -fsyntax-only \
        -std=gnu11 $W $DEFS $INC "$f" 2>&1 \
        | grep -E 'error|warning' | grep -v -E 'machine/endian.h|warnings? generated' || true)
  if [ -n "$out" ]; then
    echo "== $f"; echo "$out"; status=1
  else
    echo "ok $(basename "$f")"
  fi
done
exit $status
